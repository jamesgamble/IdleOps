type Asset = Pick<
  Resource,
  "id" | "name" | "purpose" | "importance" | "dependsOn"
> & { profile: keyof typeof profiles };

function at(
  siteId: SiteId,
  cloudId: CloudId | null,
  assets: readonly Asset[],
): Resource[] {
  return assets.map(({ profile, ...asset }) => ({
    ...asset,
    siteId,
    cloudId,
    ...profiles[profile],
  }));
}

